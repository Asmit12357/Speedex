import {
  Activity,
  ArrowRight,
  RotateCcw,
  History,
  Info,
  Clock,
  Wifi,
  AlertTriangle,
} from 'lucide-react';
import type { PageId, NetworkInput, PredictionResult } from '../../types';
import './Results.css';

interface ResultsProps {
  result: PredictionResult | null;
  input: NetworkInput | null;
  onNavigate: (page: PageId) => void;
}

export default function Results({ result, input, onNavigate }: ResultsProps) {
  if (!result || !input) {
    return (
      <div className="results">
        <header>
          <h1 className="page-title">Prediction Results</h1>
          <p className="page-subtitle">Estimated network performance metrics</p>
        </header>

        <div className="card empty-state">
          <Activity size={48} />
          <h3>No Analysis Results Yet</h3>
          <p>
            Submit your network measurements in the Network Analyzer to view
            predicted download speeds, quality classification, and factor breakdowns.
          </p>
          <button
            type="button"
            className="btn btn--primary"
            onClick={() => onNavigate('analyzer')}
          >
            Open Network Analyzer
            <ArrowRight size={16} />
          </button>
        </div>
      </div>
    );
  }

  const qualityClass = `quality-badge quality-badge--${result.quality.toLowerCase()}`;

  const formattedDate = new Date().toLocaleTimeString([], {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });

  return (
    <div className="results">
      <header>
        <h1 className="page-title">Prediction Results</h1>
        <p className="page-subtitle">
          Estimated network performance based on submitted parameters
        </p>
      </header>

      {/* Illustrative Disclaimer */}
      <div className="disclaimer">
        <Info size={16} style={{ flexShrink: 0, marginTop: 1 }} />
        <span>
          Illustrative result produced by a deterministic demo heuristic. Values are
          simulated for testing and are not generated by a trained ML model.
        </span>
      </div>

      {/* Hero: Speed & Quality */}
      <div className="results__hero">
        <span className="card__title" style={{ marginBottom: 0 }}>
          Estimated Download Speed
        </span>
        <div className="results__speed">
          <span className="results__speed-value">{result.downloadSpeed}</span>
          <span className="results__speed-unit">Mbps</span>
        </div>
        <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
          <span className={qualityClass}>{result.quality}</span>
          <span className="demo-badge">Demo Heuristic</span>
        </div>
      </div>

      {/* Submitted Parameters Summary */}
      <div className="card">
        <div className="card__title">Submitted Measurements</div>
        <div className="results__summary-grid">
          <div className="results__summary-item">
            <span className="results__summary-label">Latency</span>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <Clock size={16} color="var(--accent-blue)" />
              <span className="results__summary-value">{input.latency}</span>
              <span className="results__summary-unit">ms</span>
            </div>
          </div>

          <div className="results__summary-item">
            <span className="results__summary-label">Jitter</span>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <Activity size={16} color="var(--accent-indigo)" />
              <span className="results__summary-value">{input.jitter}</span>
              <span className="results__summary-unit">ms</span>
            </div>
          </div>

          <div className="results__summary-item">
            <span className="results__summary-label">Packet Loss</span>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <AlertTriangle size={16} color="var(--accent-red)" />
              <span className="results__summary-value">{input.packetLoss}</span>
              <span className="results__summary-unit">%</span>
            </div>
          </div>

          <div className="results__summary-item">
            <span className="results__summary-label">Signal Strength</span>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <Wifi size={16} color="var(--accent-cyan)" />
              <span className="results__summary-value">{input.signalStrength}</span>
              <span className="results__summary-unit">{input.signalUnit}</span>
            </div>
          </div>
        </div>
      </div>

      {/* Contributing Factors */}
      {result.factors && result.factors.length > 0 && (
        <div className="card">
          <div className="card__title">Factor Impact Breakdown</div>
          <ul className="results__factors-list">
            {result.factors.map((factor, index) => (
              <li key={index} className="results__factor">
                <span
                  className={`results__factor-dot results__factor-dot--${factor.impact}`}
                />
                <span className="results__factor-label">{factor.label}</span>
                <span className="results__factor-value">{factor.value}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Simulated Explanation */}
      <div className="card">
        <div className="card__title">Simulated Evaluation Summary</div>
        <p className="results__explanation">{result.explanation}</p>
      </div>

      {/* Timestamp */}
      <div className="results__timestamp">
        Evaluated at {formattedDate} (Session Demo)
      </div>

      {/* Actions */}
      <div className="results__actions" style={{ gap: '12px' }}>
        <button
          type="button"
          className="btn btn--secondary"
          onClick={() => onNavigate('analyzer')}
        >
          <RotateCcw size={16} />
          Analyze Another
        </button>
        <button
          type="button"
          className="btn btn--ghost"
          onClick={() => onNavigate('history')}
        >
          <History size={16} />
          View History
        </button>
      </div>
    </div>
  );
}
